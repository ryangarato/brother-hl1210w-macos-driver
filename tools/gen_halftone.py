#!/usr/bin/env python3
"""Generate src/halftone_tables.h for rastertohl1210w.

Usage: gen_halftone.py [LUT_DIR] > halftone_tables.h

LUT_DIR is the "Brother LUT" folder of a Brother monochrome laser driver
package you already have (for example from the expanded installer payload, or
/Library/Printers/Brother/Brother LUT when that driver is installed).  It holds
the halftone screens the printer was tuned with, as small "BRML" files:

    "BRML" "00RR" "00CC" <RR x CC threshold bytes>      (RR = CC = 32)

When LUT_DIR is missing or incomplete, generic clustered-dot screens are
generated instead, so the driver always builds and prints; tones are then a
little less faithful than with the tuned screens.
"""
import math
import os
import sys

SIZE = 32

# (table name, BRML file, fallback cell period in pixels)
SCREENS = [
    ("300 dpi, graphics", "0300-G12.bin", 8),
    ("300 dpi, text", "0300-T12.bin", 4),
    ("600 dpi, graphics", "0600-G12.bin", 8),
    ("600 dpi, text", "0600-T12.bin", 4),
    ("1200 dpi, graphics", "HQ1200-G12.bin", 16),
    ("1200 dpi, text", "HQ1200-T12.bin", 8),
]


def read_brml(path):
    with open(path, "rb") as f:
        data = f.read()
    if len(data) < 12 or data[:4] != b"BRML":
        raise ValueError("not a BRML screen file")
    rows = int(data[6:8])
    cols = int(data[10:12])
    if rows != SIZE or cols != SIZE:
        raise ValueError("unexpected screen size %dx%d" % (rows, cols))
    body = data[12:12 + rows * cols]
    if len(body) != rows * cols:
        raise ValueError("truncated screen file")
    return list(body)


def clustered_dot(period):
    """45 degree clustered-dot screen with the given cell period."""
    cells = []
    for y in range(SIZE):
        for x in range(SIZE):
            u = (x + y) * 2.0 * math.pi / period
            v = (x - y) * 2.0 * math.pi / period
            # Dots grow from the cell centres; a tiny position-dependent term
            # orders pixels that the spot function rates equally.
            spot = math.cos(u) + math.cos(v)
            tie = ((x * 7 + y * 13) % 31) / 1.0e4
            cells.append((-(spot + tie), y * SIZE + x))
    cells.sort()
    table = [0] * (SIZE * SIZE)
    for rank, (_, index) in enumerate(cells):
        table[index] = rank * 255 // (SIZE * SIZE)
    return table


def main():
    lut_dir = sys.argv[1] if len(sys.argv) > 1 else ""
    tables = []
    tuned = 0

    for label, filename, period in SCREENS:
        table = None
        if lut_dir:
            try:
                table = read_brml(os.path.join(lut_dir, filename))
                tuned += 1
            except (OSError, ValueError) as err:
                sys.stderr.write("gen_halftone: %s: %s; using a generic screen\n"
                                 % (filename, err))
        if table is None:
            table = clustered_dot(period)
        tables.append((label, table))

    if tuned == len(SCREENS):
        source = "tuned screens from the Brother driver package"
    elif tuned == 0:
        source = "generic clustered-dot screens"
    else:
        source = "mixed tuned and generic screens"

    out = sys.stdout
    out.write("/* Generated by tools/gen_halftone.py - do not edit. */\n")
    out.write("#ifndef HL1210W_HALFTONE_TABLES_H\n")
    out.write("#define HL1210W_HALFTONE_TABLES_H\n\n")
    out.write('#define BR_SCREEN_SOURCE "%s"\n\n' % source)
    out.write("static const uint8_t br_screen_tables[BR_SCREEN_COUNT]"
              "[BR_MATRIX_SIZE * BR_MATRIX_SIZE] = {\n")
    for label, table in tables:
        out.write("    { /* %s */\n" % label)
        for row in range(SIZE):
            values = table[row * SIZE:(row + 1) * SIZE]
            out.write("        " + ",".join("%3d" % v for v in values) + ",\n")
        out.write("    },\n")
    out.write("};\n\n#endif /* HL1210W_HALFTONE_TABLES_H */\n")


if __name__ == "__main__":
    main()
